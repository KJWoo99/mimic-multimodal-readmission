#!/bin/sh
# CXR 영상 이어받기: 중단 지점부터 재개하고, 끝나면 전체 디코딩으로 무결성을 검사한다.
cd "$(dirname "$0")/.." || exit 1
echo "======================================================================"
echo "  MIMIC-CXR 영상 다운로드 (이어받기)"
echo "======================================================================"
echo "  * 이미 받은 파일은 건너뛰고 없는 것만 받습니다."
echo "  * 사용자명과 비밀번호를 입력하세요."
echo "  * 완료될 때까지 이 창을 닫지 마세요."
echo "======================================================================"
echo ""
sh scripts/download_mimic.sh images 8
STATUS=$?
echo ""
echo "======================================================================"
if [ $STATUS -eq 0 ]; then
  echo "  다운로드 종료. 무결성 검사(전체 디코딩)를 이어서 돌립니다."
  echo "======================================================================"
  python scripts/verify_cxr.py --deep --workers 12
else
  echo "  다운로드가 오류로 끝났습니다 (exit $STATUS)."
  echo "======================================================================"
fi
echo ""
echo "=== 끝났습니다. 창은 닫으셔도 됩니다. ==="
read -r _
